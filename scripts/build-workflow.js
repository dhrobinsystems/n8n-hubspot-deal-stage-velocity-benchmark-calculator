#!/usr/bin/env node
'use strict';

/**
 * scripts/build-workflow.js
 * ---------------------------------------------------------------------------
 * Compiles src/config.js and src/velocityEngine.js into the n8n Code nodes of
 * workflow.json, so the JavaScript that runs in n8n is exactly the JavaScript
 * covered by the tests.
 *
 *   node scripts/build-workflow.js           write workflow.json
 *   node scripts/build-workflow.js --check   exit 1 if workflow.json is stale (CI)
 *   node scripts/build-workflow.js --stdout  print instead of writing
 *
 * Credentials are placeholders (REPLACE_WITH_... IDs). After import, select your
 * own HubSpot, Slack and Google Sheets credentials on the highlighted nodes.
 *
 * DISCLAIMER: provided "AS IS", without warranty of any kind. See DISCLAIMER.md.
 * ---------------------------------------------------------------------------
 */

const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const ROOT = path.resolve(__dirname, '..');
const OUTPUT = path.join(ROOT, 'workflow.json');
const PKG = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));
const HUBSPOT_API = 'https://api.hubapi.com';

const CREDENTIALS = Object.freeze({
  hubspot: { hubspotAppToken: { id: 'REPLACE_WITH_HUBSPOT_CREDENTIAL_ID', name: 'HubSpot Private App Token (placeholder)' } },
  slack: { slackApi: { id: 'REPLACE_WITH_SLACK_CREDENTIAL_ID', name: 'Slack Bot Token (placeholder)' } },
  sheets: { googleSheetsOAuth2Api: { id: 'REPLACE_WITH_GOOGLE_SHEETS_CREDENTIAL_ID', name: 'Google Sheets OAuth2 (placeholder)' } },
});

const RETRY = Object.freeze({ retryOnFail: true, maxTries: 3, waitBetweenTries: 3000 });

function stableId(seed) {
  const h = crypto.createHash('sha1').update(`velocity-benchmark:${seed}`).digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
}

function readModule(relPath) {
  const source = fs.readFileSync(path.join(ROOT, relPath), 'utf8');
  const code = source.split('\n').filter((line) => !/^\s*(\*|\/\/|\/\*)/.test(line));
  if (code.some((line) => /\brequire\s*\(/.test(line))) {
    throw new Error(`${relPath} must not call require(); it is inlined into n8n Code nodes.`);
  }
  return source.trimEnd();
}

function buildPreamble() {
  return [
    `// ===== AUTO-GENERATED by scripts/build-workflow.js (v${PKG.version}). Do not edit in n8n. =====`,
    '// Edit src/config.js or src/velocityEngine.js, run `npm run build`, then re-import workflow.json.',
    '// DISCLAIMER: provided "AS IS" without warranty. See DISCLAIMER.md.',
    'const __loadModule = (factory) => { const module = { exports: {} }; factory(module, module.exports); return module.exports; };',
    '',
    '// ---- src/config.js ----',
    'const Config = __loadModule(function (module, exports) {',
    readModule('src/config.js'),
    '});',
    '',
    '// ---- src/velocityEngine.js ----',
    'const Engine = __loadModule(function (module, exports) {',
    readModule('src/velocityEngine.js'),
    '});',
    '',
    '// ---- n8n runtime helpers ----',
    '/** Copy only known keys from $env; tolerates N8N_BLOCK_ENV_ACCESS_IN_NODE=true. */',
    'function __readEnv() {',
    '  const env = {};',
    '  let source;',
    '  try { source = $env; } catch (err) { source = undefined; }',
    '  if (!source) return env;',
    '  for (const key of Config.ENV_KEYS) {',
    '    try {',
    '      const value = source[key];',
    "      if (value !== undefined && value !== null && value !== '') env[key] = String(value);",
    '    } catch (err) { /* blocked or missing: defaults apply */ }',
    '  }',
    '  return env;',
    '}',
    'function __runId() {',
    '  try { return $execution && $execution.id ? String($execution.id) : null; } catch (err) { return null; }',
    '}',
    'function __now(config) {',
    '  return config.asOf ? new Date(config.asOf) : new Date();',
    '}',
    '',
  ].join('\n');
}

const ENTRIES = {
  loadConfig: `// ===== ENTRY: Load Configuration =====
// Fail fast: invalid settings stop the run before any HubSpot request is made.
const config = Config.loadConfig(__readEnv());
config.warnings.forEach((w) => console.log('[velocity] config warning: ' + Engine.redact(w)));
return [{ json: { sandbox: config.sandboxMode, runId: __runId(), asOf: __now(config).toISOString(), configWarnings: config.warnings.map(Engine.redact) } }];
`,

  buildSearch: `// ===== ENTRY: Build Deal Search =====
const config = Config.loadConfig(__readEnv());
const response = ($input.first() && $input.first().json) || {};
if (response.error) {
  // Without pipeline definitions there is nothing to benchmark: stop with a clear, redacted message.
  throw new Error('Could not load HubSpot deal pipelines: ' + Engine.redact(response.error.message || JSON.stringify(response.error)));
}
const pipelines = Engine.normalizePipelines(response, config);
if (pipelines.length === 0) {
  console.log('[velocity] No matching deal pipelines with stages found (check PIPELINE_IDS). Nothing to analyse.');
  return []; // explicit fallback: end the execution cleanly
}
const request = Engine.buildDealSearchRequest(pipelines, config, __now(config));
return [{
  json: {
    searchBody: request.body,
    windowStart: request.windowStart,
    pipelineCount: pipelines.length,
    stageCount: pipelines.reduce((n, p) => n + p.stages.length, 0),
    propertyCount: request.body.properties.length,
  },
}];
`,

  compute: `// ===== ENTRY: Compute Velocity Benchmarks =====
const config = Config.loadConfig(__readEnv());
const runId = __runId();
let pipelinesJson = {};
let searchMeta = {};
try { pipelinesJson = $('HubSpot Get Deal Pipelines').first().json || {}; } catch (err) { pipelinesJson = {}; }
try { searchMeta = $('Build Deal Search').first().json || {}; } catch (err) { searchMeta = {}; }
try {
  const pipelines = Engine.normalizePipelines(pipelinesJson, config);
  const fetched = Engine.extractDeals($input.all());
  const report = Engine.computeBenchmarks(fetched.deals, pipelines, config, __now(config), {
    runId,
    windowStart: searchMeta.windowStart || null,
    fetchErrors: fetched.errors,
  });
  report.status = fetched.rateLimited ? 'PARTIAL_RATE_LIMITED' : fetched.errors.length > 0 ? (fetched.deals.length > 0 ? 'PARTIAL_FETCH_ERROR' : 'FETCH_ERROR') : 'OK';
  report.sandbox = config.sandboxMode;
  return [{ json: report }];
} catch (err) {
  return [{ json: { kind: 'benchmark_report', status: 'ENGINE_ERROR', sandbox: config.sandboxMode, runId, error: Engine.redact(err && err.message ? err.message : String(err)), pipelines: [] } }];
}
`,

  dryRun: `// ===== ENTRY: Dry-Run Telemetry =====
// SANDBOX_MODE=true: log the report instead of posting to Slack or Google Sheets.
const config = Config.loadConfig(__readEnv());
const report = ($input.first() && $input.first().json) || {};
if (report.status === 'ENGINE_ERROR') {
  console.log('[velocity] DRY RUN engine error: ' + report.error);
  return [{ json: { kind: 'dry_run_report', status: 'ENGINE_ERROR', error: report.error } }];
}
try {
  const dry = Engine.buildDryRunReport(report, config);
  dry.lines.forEach((line) => console.log(line));
  return [{ json: Object.assign(dry, { status: report.status }) }];
} catch (err) {
  return [{ json: { kind: 'dry_run_report', status: 'REPORT_ERROR', error: Engine.redact(err && err.message ? err.message : String(err)) } }];
}
`,

  slack: `// ===== ENTRY: Format Slack Report =====
const config = Config.loadConfig(__readEnv());
if (!config.delivery.slackEnabled) return []; // Slack delivery disabled
const report = ($input.first() && $input.first().json) || {};
if (report.status === 'ENGINE_ERROR' || !Array.isArray(report.pipelines)) {
  const text = ':warning: Deal velocity benchmark run failed: ' + (report.error || 'no report produced') + '. Check the n8n execution log.';
  const blocks = [{ type: 'section', text: { type: 'mrkdwn', text } }];
  return [{ json: { channel: config.delivery.slackChannel, text, blocks, blocksJson: JSON.stringify({ blocks }) } }];
}
try {
  return Engine.buildSlackMessages(report, config).map((message) => ({ json: message }));
} catch (err) {
  const text = ':warning: Deal velocity report could not be formatted: ' + Engine.redact(err && err.message ? err.message : String(err));
  const blocks = [{ type: 'section', text: { type: 'mrkdwn', text } }];
  return [{ json: { channel: config.delivery.slackChannel, text, blocks, blocksJson: JSON.stringify({ blocks }) } }];
}
`,

  sheets: `// ===== ENTRY: Build Sheet Rows =====
const config = Config.loadConfig(__readEnv());
if (!config.delivery.sheetsEnabled) return []; // Google Sheets delivery disabled
const report = ($input.first() && $input.first().json) || {};
if (report.status === 'ENGINE_ERROR' || !Array.isArray(report.pipelines)) return [];
try {
  return Engine.buildSheetRows(report).map((row) => ({ json: row }));
} catch (err) {
  console.log('[velocity] sheet rows could not be built: ' + Engine.redact(err && err.message ? err.message : String(err)));
  return [];
}
`,
};

function codeNode(name, entry, position, notes) {
  return {
    parameters: { jsCode: `${buildPreamble()}\n${ENTRIES[entry]}` },
    id: stableId(name),
    name,
    type: 'n8n-nodes-base.code',
    typeVersion: 2,
    position,
    notes,
  };
}

function hubspotHttp(name, position, parameters, extra) {
  return Object.assign(
    {
      parameters: Object.assign({ authentication: 'predefinedCredentialType', nodeCredentialType: 'hubspotAppToken' }, parameters),
      id: stableId(name),
      name,
      type: 'n8n-nodes-base.httpRequest',
      typeVersion: 4.2,
      position,
      credentials: CREDENTIALS.hubspot,
    },
    RETRY,
    extra || {}
  );
}

